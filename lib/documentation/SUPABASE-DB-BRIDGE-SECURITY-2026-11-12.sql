-- Private server-to-server bridge metadata. Not exposed through the public Supabase Data API.
CREATE SCHEMA IF NOT EXISTS private;
CREATE TABLE IF NOT EXISTS private.radar_db_bridge_nonces (
  nonce text PRIMARY KEY,
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS radar_db_bridge_nonces_expiry ON private.radar_db_bridge_nonces(expires_at);
CREATE TABLE IF NOT EXISTS private.radar_db_bridge_audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id text NOT NULL,
  operation text NOT NULL CHECK (operation IN ('query','transaction')),
  statement_count integer NOT NULL CHECK (statement_count BETWEEN 1 AND 25),
  duration_ms integer NOT NULL DEFAULT 0,
  status text NOT NULL CHECK (status IN ('OK','ERROR')),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS radar_db_bridge_audit_created ON private.radar_db_bridge_audit(created_at DESC);