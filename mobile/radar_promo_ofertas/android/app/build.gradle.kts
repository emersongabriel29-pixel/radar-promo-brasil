// Reuse the existing private keystore; never fall back to a generated debug key.
val releaseProperties = Properties().apply {
    val propertiesFile = rootProject.file("key.properties")
    if (propertiesFile.isFile) propertiesFile.inputStream().use { load(it) }
}
fun releaseValue(environment: String, property: String): String? =
    providers.environmentVariable(environment).orNull ?: releaseProperties.getProperty(property)
val releaseStorePath = releaseValue("RADAR_RELEASE_STORE_FILE", "storeFile")
val releaseStorePassword = releaseValue("RADAR_RELEASE_STORE_PASSWORD", "storePassword")
val releaseKeyAlias = releaseValue("RADAR_RELEASE_KEY_ALIAS", "keyAlias")
val releaseKeyPassword = releaseValue("RADAR_RELEASE_KEY_PASSWORD", "keyPassword")
val releaseConfigured = listOf(releaseStorePath, releaseStorePassword, releaseKeyAlias, releaseKeyPassword)
    .all { !it.isNullOrBlank() }

val validateRadarReleaseSigning = tasks.register("validateRadarReleaseSigning") {
    group = "verification"
    description = "Check the existing signing identity without building an APK or AAB."
    doLast {
        check(releaseConfigured) { "RADAR_SIGNING_MISSING: configure the existing release keystore securely." }
        val expected = rootProject.file("signing-certificate.sha256").readText().trim().lowercase()
        check(expected.matches(Regex("[0-9a-f]{64}"))) { "RADAR_SIGNING_PIN_INVALID" }
        val certificate = try {
            val store = KeyStore.getInstance(rootProject.file(releaseStorePath!!), releaseStorePassword!!.toCharArray())
            check(store.isKeyEntry(releaseKeyAlias))
            check(store.getKey(releaseKeyAlias, releaseKeyPassword!!.toCharArray()) is java.security.PrivateKey)
            store.getCertificate(releaseKeyAlias) ?: error("missing certificate")
        } catch (_: Exception) {
            // Do not include exception details, paths, aliases or passwords in build logs.
            throw GradleException("RADAR_SIGNING_UNREADABLE: check the existing keystore configuration.")
        }
        val actual = MessageDigest.getInstance("SHA-256").digest(certificate.encoded)
            .joinToString("") { "%02x".format(it.toInt() and 0xff) }
        check(actual == expected) { "RADAR_SIGNING_MISMATCH: certificate differs from the preserved app identity." }
        logger.lifecycle("Radar release signing identity verified; no application artifact generated by this task.")
    }
}
// Every release task, including package/bundle/assemble, must pass the same guard.
tasks.configureEach {
    if (name.contains("release", ignoreCase = true) && name != "validateRadarReleaseSigning") {
        dependsOn(validateRadarReleaseSigning)
    }
}

